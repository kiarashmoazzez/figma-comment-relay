/**
 * Minimal deterministic build: concatenate the pure matcher before the Figma
 * main-thread runtime. The plugin UI remains a standalone HTML artifact.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const matcher = await readFile(join(root, "src", "matcher.js"), "utf8");
const plugin = await readFile(join(root, "src", "plugin-main.js"), "utf8");
const banner = `// Generated by scripts/build.mjs. Edit files in src/ instead.\n`;

await mkdir(join(root, "dist"), { recursive: true });
await writeFile(join(root, "dist", "code.js"), `${banner}${matcher}\n\n${plugin}\n`);

console.log("Built dist/code.js");
